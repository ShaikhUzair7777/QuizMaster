-- Curated, non-playable topic catalog for on-demand AI quiz generation.
-- This table is separate from quizzes, so repeatable seeding never changes user quizzes.

CREATE TABLE IF NOT EXISTS public.learning_topics (
    slug TEXT PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    category VARCHAR(80) NOT NULL,
    difficulty VARCHAR(20) NOT NULL
        CHECK (difficulty IN ('Beginner', 'Intermediate', 'Advanced')),
    description TEXT NOT NULL,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.learning_topics ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Service role reads learning topics" ON public.learning_topics;
CREATE POLICY "Service role reads learning topics" ON public.learning_topics
    FOR SELECT USING (auth.role() = 'service_role');
GRANT SELECT ON public.learning_topics TO service_role;

